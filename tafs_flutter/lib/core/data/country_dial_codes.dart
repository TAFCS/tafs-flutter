/// A country's international dialling code, keyed by ISO 3166-1 alpha-2.
class CountryDialCode {
  final String name;
  final String dialCode;
  final String iso2;

  const CountryDialCode(this.name, this.dialCode, this.iso2);

  /// Regional-indicator flag emoji derived from the ISO2 code.
  String get flagEmoji {
    return iso2.toUpperCase().codeUnits.map((c) => String.fromCharCode(0x1F1E6 + (c - 0x41))).join();
  }
}

